// Generates supabase/seed.sql from the same seed data the demo mode uses,
// so a fresh Supabase project starts with identical content.
// Run: node scripts/generate-seed-sql.mjs

import { writeFileSync } from "node:fs";

const { SEED_DB } = await import("../src/lib/seed.ts");

const q = (v) => (v === undefined || v === null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => (v === undefined || v === null ? "null" : `'${JSON.stringify(v).replaceAll("'", "''")}'::jsonb`);

let sql = "-- Generated by scripts/generate-seed-sql.mjs — do not edit by hand.\n\n";

sql += "insert into public.categories (id, name, slug, zone, sort) values\n";
sql += SEED_DB.categories
  .map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.slug)}, ${q(c.zone)}, ${c.sort})`)
  .join(",\n");
sql += "\non conflict (id) do nothing;\n\n";

sql +=
  "insert into public.projects (id, title, description, category_id, rank, status, estimated_cost, spent, progress, store_name, store_url, inspiration_image, before_image, after_image, hotspot, price_history, created_at) values\n";
sql += SEED_DB.projects
  .map(
    (p) =>
      `  (${q(p.id)}, ${q(p.title)}, ${q(p.description)}, ${q(p.categoryId)}, ${p.rank}, ${q(p.status)}, ${p.estimatedCost}, ${p.spent}, ${p.progress}, ${q(p.storeName)}, ${q(p.storeUrl)}, ${q(p.inspirationImage)}, ${q(p.beforeImage)}, ${q(p.afterImage)}, ${j(p.hotspot)}, ${j(p.priceHistory)}, ${q(p.createdAt)})`
  )
  .join(",\n");
sql += "\non conflict (id) do nothing;\n\n";

sql += "insert into public.recurring_tasks (id, name, detail, interval_days, last_done, icon) values\n";
sql += SEED_DB.tasks
  .map(
    (t) =>
      `  (${q(t.id)}, ${q(t.name)}, ${q(t.detail)}, ${t.intervalDays}, ${q(t.lastDone)}, ${q(t.icon)})`
  )
  .join(",\n");
sql += "\non conflict (id) do nothing;\n\n";

sql += `insert into public.budget (id, monthly_budget, project_fund) values (1, ${SEED_DB.budget.monthlyBudget}, ${SEED_DB.budget.projectFund})\non conflict (id) do nothing;\n`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("Wrote supabase/seed.sql");
